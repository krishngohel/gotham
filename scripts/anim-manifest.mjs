// Writes docs/design/anim-manifest.md from scripts/anim-packs.mjs, the generated pack data and
// the automated check (scripts/anim-check.mjs). Run after scripts/bake-packs.mjs.
//   node scripts/anim-manifest.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, statSync, writeFileSync, mkdtempSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { PACKS, PACK_CLIPS, DROPPED, QA_NOTES, GAPS, PACK_INTRO } from './anim-packs.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = path.join(mkdtempSync(path.join(os.tmpdir(), 'anim-manifest-')), 'check.json');
try { execFileSync(process.execPath, [path.join(ROOT, 'scripts/anim-check.mjs'), ...PACKS], { cwd: ROOT, env: { ...process.env, CHECK_JSON: tmp }, stdio: 'ignore' }); } catch { /* failures are reported in the table */ }
const check = new Map(JSON.parse(readFileSync(tmp, 'utf8')).map((r) => [r.name, r]));

const f2 = (v) => (v == null ? '–' : (+v).toFixed(2));
const evText = (d) => {
  const e = d.events ?? {};
  const keys = ['warpStart', 'contact', 'cancel', 'recover', 'down', 'getUpStart'].filter((k) => k in e && !(k === 'contact' && d.kind !== 'strike'));
  const parts = keys.map((k) => `${k} ${e[k] == null ? 'null' : f2(e[k])}`);
  if (e.footL?.length || e.footR?.length) parts.push(`feet ${e.footL?.length ?? 0}L/${e.footR?.length ?? 0}R`);
  if (d.pair) parts.push(`pair ${d.pair.with} @(${d.pair.offset.join(', ')})`);
  return parts.join(', ') || '–';
};
const rootText = (d) => {
  const n = d.root.length;
  const x = d.root[n - 2], z = d.root[n - 1];
  const dist = Math.hypot(x, z);
  return dist < 0.1 ? 'no' : `${dist.toFixed(1)} m (${x.toFixed(1)}, ${z.toFixed(1)})`;
};
const esc = (s) => String(s).replace(/\|/g, '\\|');

let total = 0, bytes = 0;
const sections = [];
const sizes = [];
const counts = {};
for (const pack of PACKS) {
  const data = (await import(pathToFileURL(path.join(ROOT, `src/config/mocapData.${pack}.js`)).href)).MOCAP_DATA;
  const size = statSync(path.join(ROOT, 'public/assets', `anims_${pack}.glb`)).size;
  bytes += size;
  const names = Object.keys(data);
  total += names.length;
  sizes.push(`| \`anims_${pack}.glb\` | ${names.length} | ${(size / 1e6).toFixed(2)} MB | \`mocapData.${pack}.js\` | \`${{ combat2: 'loadCombat2Anims', enemies: 'loadEnemyAnims', heroes: 'loadHeroAnims', civ: 'loadCivAnims', story: 'loadStoryAnims' }[pack]}\` |`);
  const rows = [];
  for (const [k, c] of Object.entries(PACK_CLIPS).filter(([, c]) => c.pack === pack)) {
    for (const name of c.mirror ? [k, k + '_M'] : [k]) {
      const d = data[name];
      if (!d) continue;
      counts[`${pack}/${c.cat}`] = (counts[`${pack}/${c.cat}`] ?? 0) + 1;
      const chk = check.get(name);
      const q = [...(chk?.problems ?? []).map((p) => 'FAIL ' + p), ...(chk?.notes ?? []), QA_NOTES[name] ?? QA_NOTES[k] ?? ''].filter(Boolean).join('; ') || 'ok';
      const use = name.endsWith('_M') ? `mirror of ${k}` : c.use;
      rows.push(`| ${name} | ${esc(c.mixamo[0])} — ${esc(c.mixamo[1])} | ${c.cat} | ${d.kind} | ${f2(d.duration)} | ${d.loop ? 'yes' : 'no'} | ${rootText(d)} | ${evText(d)} | ${esc(use)} | ${esc(q)} |`);
    }
  }
  sections.push(`### ${pack} (\`anims_${pack}.glb\`, ${names.length} clips)\n\n${PACK_INTRO[pack] ?? ''}\n\n| clip | Mixamo source (name — description) | category | kind | dur s | loop | root motion (net) | events (s) | intended use | quality notes |\n|---|---|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`);
}

const dropped = Object.entries(DROPPED).map(([k, why]) => `| ${k} | ${PACK_CLIPS[k]?.pack ?? '?'} | ${esc(PACK_CLIPS[k]?.mixamo.join(' — ') ?? '')} | ${esc(why)} |`);
const md = `# Animation manifest (Long Night 2, workstream N)

Generated by \`node scripts/anim-manifest.mjs\` from \`scripts/anim-packs.mjs\`, the pack data
modules and \`scripts/anim-check.mjs\`. Do not edit by hand: change the table in anim-packs.mjs.

**${total} new clips in ${PACKS.length} lazy packs, ${(bytes / 1e6).toFixed(2)} MB in total.** The preloaded
\`anims_mocap.glb\` / \`mocapData.js\` (56 clips) are unchanged; their events are in the additive
\`src/config/clipEvents.js\` (\`CLIP_EVENTS[name]\`, same event names as below).

| pack | clips | size | data module | loader (\`src/actors/animPacks.js\`) |
|---|---|---|---|---|
${sizes.join('\n')}

## How to use the packs

- **Loading.** \`await loadCombat2Anims()\` (or \`loadAnimPack('combat2')\`) returns \`{ clips, data }\`:
  sanitised \`THREE.AnimationClip\`s keyed by name and the pack's \`MOCAP_DATA\`. Merge into an actor's
  clip map with \`mergePackClips(map, pack)\` (never replaces an existing clip). Loads are cached. Not
  in the preload list; Vite code-splits the data modules.
- **Data shape** is mocapData.js's (\`duration\`, \`contact\`, \`limb\`, \`reach\`, \`fps\`, \`root\` as
  [x, z] per frame) plus \`kind\` (strike | react | knockdown | getup | loco | loop | action), \`loop\`,
  \`events\` and, for the victim side of paired moves, \`pair: { with, offset: [x, z] }\` (where the
  victim's root starts relative to the attacker's, metres, attacker clip axes; +z is the
  attacker's forward only for clips baked with aim — paired clips keep Mixamo's own heading).
- **Events** (clip seconds): strikes \`warpStart\` (limb starts accelerating; open motion warping),
  \`contact\` (limb at peak reach: fire the hit), \`cancel\` (limb a quarter of the way back:
  strike→strike may transition), \`recover\` (limb slow and pose settled: any action), \`end\`;
  reactions/actions \`recover\`; knockdowns \`down\` (pelvis at the floor and still) and
  \`getUpStart\` (\`null\` = the clip ends on the floor: chain \`GetUp_Front\`/\`GetUp_Back\`);
  get-ups \`getUpStart\`, \`recover\`; everything but plain loops \`footL\`/\`footR\` (plant times,
  for audio, dust and foot locking). \`contact\` is only meaningful for \`kind: 'strike'\`.
- **Baked without easing** (\`retarget-mocap.mjs --no-ease\`): unlike anims_mocap.glb, these clips
  start and end in their own pose, not snapped to Idle_Loop over 2–5 frames. Blend in/out at
  runtime (dead blending / crossfade). They are trimmed to the motion (energy threshold) unless
  marked whole (loops, pairs, some blocks).
- **Root motion.** Horizontal hips travel is removed from the clip and given per frame in \`root\`
  (as for the existing mocap). Loops (\`loop: yes\`) are kept whole; their net root motion over one
  cycle is the locomotion speed × duration. Strikes are turned so the limb lands straight ahead
  (+z) at contact; clips flagged noaim (evades, reactions, actions, pairs) keep Mixamo's heading.
- **Mirrors.** \`_M\` clips are the same move left↔right (e.g. \`React_Heavy_Right_M\` = hit from the
  left, \`KD_FromRight_M\` = falls to his right).
- **Directional reaction table** (combat2): light — front \`React_Light_Front\`/\`Front2\`, back
  \`React_Light_Back\`, left \`React_Light_Left\`, right \`React_Light_Right\`; heavy — front
  \`React_Heavy_Front\`, back \`React_Heavy_Back\`, right \`React_Heavy_Right\`, left
  \`React_Heavy_Right_M\`; knockdown — from front \`KD_FromFront\` (lands on back → \`GetUp_Back\`),
  from back \`KD_FromBack\` (lands on face → \`GetUp_Front\`), from right \`KD_FromRight\`, from left
  \`KD_FromRight_M\`; launch \`KD_Launch\`/\`KD_FlyBack\` → \`Air_Flail\` loop while airborne →
  \`Air_HardLand\`; stun \`Stun_Dizzy\`; additive flinch sources \`React_Flinch_L/R\` (use the first
  ~0.3 s with \`AnimationUtils.makeClipAdditive\`).

## Clips

${sections.join('\n')}
## Dropped clips

${dropped.length ? `| clip | pack | Mixamo source | why |\n|---|---|---|---|\n${dropped.join('\n')}` : 'None.'}

## Gaps and fallbacks (could not get from Mixamo)

${GAPS.map((g) => `- ${g}`).join('\n')}

## Counts per category

${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(' · ')}
`;
writeFileSync(path.join(ROOT, 'docs/design/anim-manifest.md'), md);
console.log(`wrote docs/design/anim-manifest.md: ${total} clips, ${(bytes / 1e6).toFixed(2)} MB`);
